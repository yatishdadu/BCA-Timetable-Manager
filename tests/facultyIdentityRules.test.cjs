const assert = require('node:assert/strict');
const { test } = require('node:test');
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const cli = path.resolve(__dirname, '..', 'node_modules', 'esbuild', 'bin', 'esbuild');
const compiled = path.join(os.tmpdir(), `bca-faculty-rules-${process.pid}.cjs`);
execFileSync(process.execPath, [cli, path.resolve(__dirname, '..', 'src/main/facultyIdentityRules.ts'), '--bundle', '--platform=node', '--format=cjs', `--outfile=${compiled}`], { stdio: 'pipe' });
const { normalizeFacultyCode, canPermanentlyDelete } = require(compiled);
process.on('exit', () => { try { fs.unlinkSync(compiled); } catch {} });
test('official ID preserves leading zeroes and normalizes case', () => assert.equal(normalizeFacultyCode('  emp-0012  '), 'EMP-0012'));
test('coordinator-issued guest ID is accepted', () => assert.equal(normalizeFacultyCode('guest/07'), 'GUEST/07'));
test('ID cannot be blank', () => assert.throws(() => normalizeFacultyCode('  ')));
test('ID cannot contain punctuation or spaces', () => assert.throws(() => normalizeFacultyCode('EMP 01')));
test('ID length cannot exceed 32', () => assert.throws(() => normalizeFacultyCode('A'.repeat(33))));
test('active record cannot be permanently deleted', () => assert.equal(canPermanentlyDelete(true, []), false));
test('inactive record with allocations cannot be deleted', () => assert.equal(canPermanentlyDelete(false, ['Subject allocation']), false));
test('inactive record with stored timetable cannot be deleted', () => assert.equal(canPermanentlyDelete(false, ['Saved timetable draft']), false));
test('inactive unused record can be permanently deleted', () => assert.equal(canPermanentlyDelete(false, []), true));
